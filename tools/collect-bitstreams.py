#!/usr/bin/env python3
"""Collect built FPGA bitstreams into an indexed, self-describing directory.

Chipyard names every bitstream after its harness, so `Arty100THarness.bit`
appears once per config and the files are indistinguishable once separated from
their directories. This copies them out under names that carry board and config,
and writes an index recording what each one actually is: part, resources,
timing, size, checksum, and the source revisions it was built from.

Bitstreams are COPIED, not moved: `rb program` and `rb chipyard path` resolve
them in place under generated-src, and moving them would break both.

Usage:
  tools/collect-bitstreams.py [--out bitstreams]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import subprocess
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GENERATED = ROOT / "backends" / "chipyard" / "fpga" / "generated-src"

# Device capacities, as quoted elsewhere in this repository.
DEVICES = {
    "arty100t": dict(lut=63400, ff=126800, ramb36=135, dsp=240),
    "arty200t": dict(lut=134600, ff=269200, ramb36=365, dsp=740),
    "ku040": dict(lut=242400, ff=484800, ramb36=600, dsp=1920),
}
BOARD_OF_PACKAGE = {
    "chipyard.fpga.arty100t": "arty100t",
    "chipyard.fpga.arty200t": "arty200t",
    "chipyard.fpga.ku040": "ku040",
    "chipyard.fpga.vcu118": "vcu118",
}


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def git_rev(path: Path) -> str | None:
    try:
        out = subprocess.run(
            ["git", "-C", str(path), "rev-parse", "--short", "HEAD"],
            capture_output=True, text=True, timeout=30,
        )
        return out.stdout.strip() or None
    except (OSError, subprocess.SubprocessError):
        return None


def git_dirty(path: Path) -> bool | None:
    try:
        out = subprocess.run(
            ["git", "-C", str(path), "status", "--porcelain"],
            capture_output=True, text=True, timeout=60,
        )
        return bool(out.stdout.strip())
    except (OSError, subprocess.SubprocessError):
        return None


def parse_utilization(path: Path) -> dict:
    """Totals row plus the device and date the report header records."""
    if not path.is_file():
        return {}
    text = path.read_text(errors="ignore")
    out: dict = {}
    device = re.search(r"^\|\s*Device\s*:\s*(\S+)", text, re.M)
    if device:
        out["part"] = device.group(1)
    date = re.search(r"^\|\s*Date\s*:\s*(.+?)\s*$", text, re.M)
    if date:
        out["built"] = date.group(1)

    header = None
    for line in text.splitlines():
        if header is None and "Total LUTs" in line and "Instance" in line:
            header = [c.strip() for c in line.split("|")]
            continue
        # The totals row is the top-level harness instance.
        if header and re.match(r"^\|\s*\S*Harness\s*\|", line):
            cells = [c.strip() for c in line.split("|")]
            try:
                for key, col in (("lut", "Total LUTs"), ("ff", "FFs"),
                                 ("ramb36", "RAMB36"), ("dsp", "DSP Blocks")):
                    out[key] = int(cells[header.index(col)])
            except (ValueError, IndexError):
                pass
            break
    return out


def parse_timing(path: Path) -> dict:
    if not path.is_file():
        return {}
    text = path.read_text(errors="ignore")
    out = {"timing_met": "All user specified timing constraints are met" in text}
    row = re.search(r"^\s*(-?\d+\.\d+)\s+(-?\d+\.\d+)\s+(\d+)\s+(\d+)\s+(-?\d+\.\d+)", text, re.M)
    if row:
        out["wns_ns"] = float(row.group(1))
        out["whs_ns"] = float(row.group(5))
    return out



def render_readme(manifest: dict) -> str:
    entries = manifest["bitstreams"]
    rev = manifest["source_revisions"]
    failing = [e for e in entries if e.get("timing_met") is False]

    lines = [
        "# RiskyBird FPGA bitstreams",
        "",
        "Prebuilt bitstreams, published so a local development machine can fetch them",
        "without a Vivado run. Generated by `tools/collect-bitstreams.py` in riskybird-dev;",
        "do not hand-edit this file or `manifest.json`.",
        "",
        f"Snapshot taken **{manifest['generated_utc']}**.",
        "",
        "## Naming",
        "",
        "Chipyard names every bitstream after its harness, so the originals are all",
        "`Arty100THarness.bit` / `KU040Harness.bit` and are indistinguishable once moved.",
        "Here each file is `<board>/<board>.<Config>.bit`, which stays unambiguous even if",
        "the files are flattened into one directory.",
        "",
    ]

    if failing:
        lines += [
            "## Read this before programming anything",
            "",
            f"**{len(failing)} of {len(entries)} bitstreams here do not meet timing.** They are",
            "design-space-exploration probes from `rb area run`, kept because their area numbers",
            "are the record behind the KU040 accelerator work -- not because they are deployable.",
            "Programming one onto hardware may produce wrong results at any clock rate.",
            "",
        ]
        for e in failing:
            lines.append(f"- `{e['file']}` --- WNS **{e['wns_ns']} ns**")
        lines += ["", "Every other bitstream below met all timing constraints.", ""]

    lines += [
        "## Provenance",
        "",
        "| Source | Revision |",
        "|---|---|",
        f"| riskybird-dev | `{rev.get('riskybird-dev')}` |",
        f"| chipyard | `{rev.get('chipyard')}` |",
        f"| fpga-shells | `{rev.get('fpga-shells')}` |",
        "",
    ]
    if rev.get("riskybird-dev_dirty"):
        lines += [
            "> **The riskybird-dev working tree had uncommitted changes when these were built.**",
            "> The revision above therefore does not fully identify the source. Treat these as",
            "> snapshots of work in progress rather than reproducible artifacts.",
            "",
        ]

    lines += [
        "## Index",
        "",
        "| Board | Config | Part | LUT | Timing | Built | File |",
        "|---|---|---|---:|---|---|---|",
    ]
    for e in entries:
        lut = f"{e['lut']:,} ({e['lut_pct']}%)" if "lut" in e and "lut_pct" in e else "-"
        met = "met" if e.get("timing_met") else f"**FAILS** ({e.get('wns_ns')} ns)"
        lines.append(
            f"| {e['board']} | `{e['config']}` | {e.get('part','-')} | {lut} | {met} "
            f"| {e.get('built','-')} | `{e['file']}` |"
        )

    lines += [
        "",
        "## Using one",
        "",
        "```console",
        "git clone git@github.com:lorenshung/bitstream.git",
        "openFPGALoader --board <profile> --bitstream bitstream/arty100t/arty100t.RocketArty100TOspiConfig.bit",
        "```",
        "",
        "To use one with `rb program`, copy it back over the path `rb chipyard path` reports",
        "for that board and config; `rb` resolves bitstreams inside Chipyard's generated-src",
        "tree, not from here.",
        "",
        "## Regenerating",
        "",
        "```console",
        "tools/collect-bitstreams.py --out /path/to/bitstream",
        "```",
        "",
        "Bitstreams are copied, never moved: `rb program` and `rb chipyard path` resolve them",
        "in place under `generated-src`.",
        "",
        "## A note on repository size",
        "",
        f"This snapshot is {sum(e['bytes'] for e in entries) / 1048576:.0f} MB across "
        f"{len(entries)} files. Bitstreams are incompressible and do not delta well, so every",
        "refresh adds roughly its full size to history again. If this is refreshed often,",
        "move it to Git LFS or periodically squash history.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "bitstreams"))
    args = ap.parse_args()
    out_dir = Path(args.out)

    entries = []
    for bit in sorted(GENERATED.glob("*/obj/*.bit")):
        # A config directory can hold two bitstreams: <Harness>.bit from
        # Chipyard's `make bitstream`, and rb_impl.bit from `make rb-impl`,
        # which routes the use_dsp-injected checkpoint `rb area run --attrs dsp`
        # measured. They are DIFFERENT DESIGNS, and for the accelerator configs
        # only the injected one fits the part at all.
        #
        # Both used to be collected to the same destination name, so which one a
        # published directory ended up carrying came down to the sort order of
        # the filenames. That happened to favour rb_impl.bit -- 'A' sorts before
        # 'r', so it was copied second and overwrote the other -- which is an
        # accident, not a decision, and it would have silently reversed if either
        # file were ever renamed. Say it instead.
        if bit.name != "rb_impl.bit" and (bit.parent / "rb_impl.bit").is_file():
            print(f"skip (superseded by rb_impl.bit): {bit.parent.parent.name}/{bit.name}")
            continue
        gen = bit.parent.parent.name
        # chipyard.fpga.<board>.<Harness>.<Config>
        match = re.match(r"^(chipyard\.fpga\.[a-z0-9]+)\.([A-Za-z0-9]+)\.(.+)$", gen)
        if not match:
            print(f"skip (unrecognised name): {gen}")
            continue
        package, harness, config = match.groups()
        board = BOARD_OF_PACKAGE.get(package, package.split(".")[-1])

        report = bit.parent / "report"
        # Two flows produce bitstreams here and they name their reports
        # differently: the standard Chipyard bitstream flow writes
        # utilization.txt, while `rb area run` writes rb_impl_utilization_hier
        # (post-route) or rb_utilization_hier (synthesis) plus rb_manifest.json.
        info = {}
        for candidate in ("utilization.txt", "rb_impl_utilization_hier.txt",
                          "rb_utilization_hier.txt"):
            info = parse_utilization(report / candidate)
            if info.get("lut") is not None:
                break
        info.update(parse_timing(report / "timing.txt"))

        rb_manifest = report / "rb_manifest.json"
        if rb_manifest.is_file():
            try:
                rb = json.loads(rb_manifest.read_text())
                info.setdefault("part", rb.get("device", {}).get("part"))
                info.setdefault("built", rb.get("synthesized_at"))
                info["flow"] = rb.get("flow", "rb-area")
                info["provenance"] = "rb area run (design-space probe)"
            except (OSError, ValueError):
                pass
        else:
            info.setdefault("flow", "chipyard bitstream")

        cap = DEVICES.get(board)
        if cap and "lut" in info:
            info["lut_pct"] = round(100 * info["lut"] / cap["lut"], 1)
            info["ff_pct"] = round(100 * info["ff"] / cap["ff"], 1)

        dest_name = f"{board}.{config}.bit"
        dest = out_dir / board / dest_name
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(bit, dest)

        entries.append({
            "board": board,
            "config": config,
            "harness": harness,
            "file": f"{board}/{dest_name}",
            "source": str(bit.relative_to(ROOT)),
            "bytes": dest.stat().st_size,
            "sha256": sha256(dest),
            **info,
        })
        print(f"{dest.relative_to(out_dir)}  <-  {gen}")

    manifest = {
        "generated_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "source_revisions": {
            "riskybird-dev": git_rev(ROOT),
            "riskybird-dev_dirty": git_dirty(ROOT),
            "chipyard": git_rev(ROOT / "backends" / "chipyard"),
            "fpga-shells": git_rev(ROOT / "backends" / "chipyard" / "fpga" / "fpga-shells"),
        },
        "bitstreams": entries,
    }
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    (out_dir / "README.md").write_text(render_readme(manifest))
    print(f"\n{len(entries)} bitstreams -> {out_dir}")
    failing = [e for e in entries if e.get("timing_met") is False]
    if failing:
        print(f"WARNING: {len(failing)} of {len(entries)} do not meet timing "
              f"(flagged in README.md and manifest.json)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
